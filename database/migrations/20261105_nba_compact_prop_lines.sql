-- NBA compact T-60 feature lines and short-retention inference quotes.
-- Entirely additive: no legacy raw/archive or active linker-state DDL/data changes.
BEGIN;
SET lock_timeout = '2s';
SET statement_timeout = '30s';

CREATE TABLE IF NOT EXISTS public.nba_player_props_inference (
    staging_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    api_game_id text NOT NULL,
    api_player_name text NOT NULL,
    bookmaker text NOT NULL,
    market_key text NOT NULL,
    outcome_label text NOT NULL,
    line numeric,
    odds_american integer NOT NULL,
    commence_time timestamptz NOT NULL,
    home_team text,
    away_team text,
    inserted_at timestamptz NOT NULL DEFAULT now(),
    market_last_update timestamptz,
    bookmaker_last_update timestamptz,
    bookmaker_name text,
    snapshot_time timestamptz NOT NULL,
    game_id text,
    player_id bigint,
    team_id bigint,
    requested_snapshot_time timestamptz,
    source_snapshot_time timestamptz NOT NULL,
    source_kind text NOT NULL,
    observed_at timestamptz NOT NULL,
    CONSTRAINT nba_player_props_inference_source_kind
        CHECK (source_kind IN ('live', 'historical')),
    CONSTRAINT nba_player_props_inference_clock_order
        CHECK (source_snapshot_time < commence_time AND snapshot_time = source_snapshot_time),
    CONSTRAINT nba_player_props_inference_identity_shape
        CHECK (game_id IS NULL OR game_id ~ '^[0-9]{10}$')
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_nba_props_inference_quote
    ON public.nba_player_props_inference
    (api_game_id, api_player_name, bookmaker, market_key, outcome_label,
     COALESCE(line, -999999::numeric), source_snapshot_time);
CREATE INDEX IF NOT EXISTS idx_nba_props_inference_event_window
    ON public.nba_player_props_inference (api_game_id, commence_time, source_snapshot_time DESC, staging_id);
CREATE INDEX IF NOT EXISTS idx_nba_props_inference_linked_window
    ON public.nba_player_props_inference (game_id, player_id, market_key, commence_time, observed_at DESC)
    WHERE game_id IS NOT NULL AND player_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_nba_props_inference_retention
    ON public.nba_player_props_inference (commence_time, staging_id);

CREATE TABLE IF NOT EXISTS public.nba_props_inference_linker_state (
    state_name text PRIMARY KEY CHECK (state_name = 'nba_inference'),
    replay_floor bigint NOT NULL,
    cursor bigint NOT NULL,
    high_water bigint,
    first_unresolved_id bigint,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (replay_floor >= 0 AND cursor >= replay_floor),
    CHECK (high_water IS NULL OR high_water >= cursor),
    CHECK (first_unresolved_id IS NULL OR (
        high_water IS NOT NULL AND first_unresolved_id > replay_floor
        AND first_unresolved_id <= high_water
    ))
);
INSERT INTO public.nba_props_inference_linker_state
    (state_name, replay_floor, cursor, high_water, first_unresolved_id)
VALUES ('nba_inference', 0, 0, NULL, NULL)
ON CONFLICT (state_name) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.nba_prop_capture_tasks (
    task_id uuid PRIMARY KEY,
    api_game_id text NOT NULL,
    target_snapshot_time timestamptz NOT NULL,
    markets text[] NOT NULL,
    bookmakers text[] NOT NULL,
    selection_policy_version text NOT NULL,
    source_kind text NOT NULL,
    status text NOT NULL,
    request_count integer NOT NULL DEFAULT 0,
    credit_count integer NOT NULL DEFAULT 0,
    raw_quote_count integer NOT NULL DEFAULT 0,
    feature_row_count integer NOT NULL DEFAULT 0,
    error_message text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    completed_at timestamptz,
    CONSTRAINT nba_prop_capture_tasks_policy CHECK (selection_policy_version = 't60_v1'),
    CONSTRAINT nba_prop_capture_tasks_source CHECK (source_kind = 'historical'),
    CONSTRAINT nba_prop_capture_tasks_status CHECK (status IN ('pending', 'success', 'empty', 'error', 'unresolved')),
    CONSTRAINT nba_prop_capture_tasks_counts CHECK (
        request_count >= 0 AND credit_count >= 0 AND raw_quote_count >= 0 AND feature_row_count >= 0
    ),
    CONSTRAINT nba_prop_capture_tasks_complete CHECK (
        (status IN ('success', 'empty') AND completed_at IS NOT NULL)
        OR (status NOT IN ('success', 'empty') AND completed_at IS NULL)
    ),
    UNIQUE (api_game_id, target_snapshot_time, markets, bookmakers, selection_policy_version)
);
CREATE INDEX IF NOT EXISTS idx_nba_prop_capture_tasks_resume
    ON public.nba_prop_capture_tasks (status, target_snapshot_time, api_game_id);

CREATE TABLE IF NOT EXISTS public.nba_player_prop_feature_lines (
    game_id text NOT NULL,
    player_id bigint NOT NULL,
    market_key text NOT NULL,
    line numeric NOT NULL,
    bookmaker text NOT NULL,
    game_date date NOT NULL,
    season_id text NOT NULL,
    selection_policy_version text NOT NULL,
    decision_time timestamptz NOT NULL,
    commence_time timestamptz NOT NULL,
    source_snapshot_time timestamptz NOT NULL,
    team_id bigint,
    api_game_id text NOT NULL,
    api_player_name text NOT NULL,
    source_kind text NOT NULL,
    requested_snapshot_time timestamptz,
    market_last_update timestamptz,
    bookmaker_last_update timestamptz,
    observed_at timestamptz NOT NULL,
    fetched_at timestamptz NOT NULL DEFAULT now(),
    task_id uuid REFERENCES public.nba_prop_capture_tasks(task_id),
    source_staging_id bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (game_id, player_id, market_key, selection_policy_version),
    CONSTRAINT nba_player_prop_feature_lines_game_id CHECK (game_id ~ '^[0-9]{10}$'),
    CONSTRAINT nba_player_prop_feature_lines_policy CHECK (selection_policy_version = 't60_v1'),
    CONSTRAINT nba_player_prop_feature_lines_market CHECK (
        market_key IN ('player_points', 'player_rebounds', 'player_assists', 'player_threes')
    ),
    CONSTRAINT nba_player_prop_feature_lines_book CHECK (bookmaker IN ('draftkings', 'pinnacle')),
    CONSTRAINT nba_player_prop_feature_lines_source CHECK (source_kind IN ('live', 'historical')),
    CONSTRAINT nba_player_prop_feature_lines_positive_line CHECK (line > 0),
    CONSTRAINT nba_player_prop_feature_lines_clock_order CHECK (
        decision_time = commence_time - interval '60 minutes'
        AND source_snapshot_time <= decision_time
        AND observed_at <= decision_time
        AND source_snapshot_time < commence_time
        AND observed_at < commence_time
        AND (market_last_update IS NULL OR market_last_update <= decision_time)
        AND (bookmaker_last_update IS NULL OR bookmaker_last_update <= decision_time)
    )
);
CREATE INDEX IF NOT EXISTS idx_nba_prop_feature_lines_season_date
    ON public.nba_player_prop_feature_lines (season_id, game_date, market_key);
CREATE INDEX IF NOT EXISTS idx_nba_prop_feature_lines_game_player
    ON public.nba_player_prop_feature_lines (game_id, player_id);
CREATE INDEX IF NOT EXISTS idx_nba_prop_feature_lines_player_date
    ON public.nba_player_prop_feature_lines (player_id, game_date DESC, market_key);

ALTER TABLE public.nba_player_props_inference ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.nba_props_inference_linker_state ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.nba_prop_capture_tasks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.nba_player_prop_feature_lines ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.nba_player_props_inference FROM anon, authenticated;
REVOKE ALL ON TABLE public.nba_props_inference_linker_state FROM anon, authenticated;
REVOKE ALL ON TABLE public.nba_prop_capture_tasks FROM anon, authenticated;
REVOKE ALL ON TABLE public.nba_player_prop_feature_lines FROM anon, authenticated;
GRANT SELECT ON TABLE public.nba_player_props_inference TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.nba_player_props_inference TO postgres;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.nba_props_inference_linker_state TO postgres;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.nba_prop_capture_tasks TO postgres;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.nba_player_prop_feature_lines TO postgres;
GRANT USAGE, SELECT ON SEQUENCE public.nba_player_props_inference_staging_id_seq TO postgres;

DO $policy$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_policies
        WHERE schemaname = 'public'
          AND tablename = 'nba_player_props_inference'
          AND policyname = 'nba_player_props_inference_authenticated_read'
    ) THEN
        CREATE POLICY nba_player_props_inference_authenticated_read
            ON public.nba_player_props_inference
            FOR SELECT TO authenticated USING (true);
    END IF;
END
$policy$;

COMMENT ON TABLE public.nba_player_props_inference IS
    'Short-retention NBA raw quote staging. snapshot_time/source_snapshot_time are actual provider/observation clocks; requested_snapshot_time is never substituted for them.';
COMMENT ON TABLE public.nba_player_prop_feature_lines IS
    'One linked numeric line per game/player/market selected by fixed t60_v1 policy.';
COMMENT ON COLUMN public.nba_player_prop_feature_lines.selection_policy_version IS
    'Frozen literal t60_v1: newest eligible source clock, then market update, then draftkings before pinnacle.';

COMMIT;
